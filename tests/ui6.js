const { chromium } = require('/opt/node-tools/node_modules/playwright');
const out = process.argv[2];
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1360, height: 800 } });
  const errors = [];
  page.on('pageerror', e => errors.push('PAGEERR ' + e.message + '\n' + (e.stack || '')));
  page.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
  await page.goto('file://' + process.cwd() + '/index.html');
  await page.click('#m-help'); await page.waitForTimeout(200); await page.screenshot({ path: out + '/e0.png' }); await page.keyboard.press('Escape');
  await page.click('#m-settings'); await page.waitForTimeout(200); await page.screenshot({ path: out + '/e00.png' }); await page.keyboard.press('Escape');
  await page.click('#m-examples'); await page.waitForTimeout(200);
  await page.locator('#modal-body .li').nth(0).locator('button.go').click();
  await page.waitForTimeout(400);
  await page.evaluate(() => { const v = SS.Flight.world.active; const r = Math.hypot(v.x, v.y); v.x *= (r + 250) / r; v.y *= (r + 250) / r; v.vy = -70; });
  const frames = async (n, name) => { for (let i = 0; i < n; i++) await page.waitForTimeout(100); await page.screenshot({ path: out + '/' + name + '.png' }); };
  await frames(18, 'e1'); await frames(4, 'e2'); await frames(10, 'e3');
  await page.keyboard.press('Escape'); await page.waitForTimeout(200); await page.screenshot({ path: out + '/e4.png' });
  console.log(await page.evaluate(() => SS.Flight.world.events.filter(e => e.text).map(e => e.text).join(' | ')));
  console.log(errors.join('\n') || 'no errors');
  await browser.close();
})();
